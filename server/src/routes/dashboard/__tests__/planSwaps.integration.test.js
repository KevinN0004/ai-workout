import { afterAll, beforeAll, beforeEach, describe, expect, test } from "vitest";
import request from "supertest";
import { app } from "../../../index.js";
import { prisma } from "../../../db/prisma.js";
import { mapGeneratedPlan } from "../../../repositories/generatedPlanRepository.js";
import { generatePlan } from "../../../services/planning/generatePlan.js";
import { buildFallbackNotes, buildSafetyNotes } from "../../../services/planning/fallbackNotes.js";
import {
  buildPlanPayload,
  withPrescriptions
} from "../../../services/dashboard/planPayloadService.js";
import { SWAP_AREAS, rulesForPlan, swapOptions } from "../../../services/planning/swaps.js";

// The exercise swaps over the wire (roadmap C4,
// docs/specs/2026-11-08-exercise-swaps-design.md, "The server"): the
// alternatives, the swap and the undo, against real Postgres. Its own file
// because the auth limiter allows 25 signups a file.
//
// The plan is generated by the rules and written straight to its table, as
// the generate route saves it, rather than through /api/generate: index.js
// builds its Gemini client when it loads, so a generate call here could reach
// the real API. A beginner's two days of 30 minutes open on Monday with the
// goblet squat, a superset and its ramp-up.

const GOBLET = "Dumbbell goblet squat";
const SUMO = "Dumbbell sumo squat";
const AGE = 30;
const FIELDS = {
  goal: "Build lean strength and energy",
  environment: "Home",
  equipment: ["Dumbbells", "Adjustable bench"],
  level: "Beginner",
  days: 2,
  duration: 30,
  injuries: "None",
  focuses: []
};

const generated = () => {
  const plan = generatePlan({ ...FIELDS, health: {}, age: AGE });
  const notes = [...buildFallbackNotes(plan), ...buildSafetyNotes(plan)];
  const text = `${plan.text}\n\nCoach Notes:\n${notes.join("\n")}`;
  return { text, payload: withPrescriptions(buildPlanPayload(text), plan.week) };
};

const getCsrf = async (agent) => {
  const response = await agent.get("/api/csrf-token");
  return String(response.body?.csrfToken || "");
};

const signUp = async (agent, email) => {
  const csrfToken = await getCsrf(agent);
  const response = await agent
    .post("/api/auth/signup")
    .set("X-CSRF-Token", csrfToken)
    .send({
      email,
      password: "StrongPass123!",
      profile: {
        firstName: "Jo",
        lastName: "Vance",
        age: AGE,
        heightCm: 170,
        weightKg: 70,
        sex: "Female",
        activity: "Moderate"
      }
    });
  expect(response.status).toBe(200);
  return getCsrf(agent);
};

// The plan saved for the user with `email`, as the generate route saves one.
const savePlan = async (email, { structured = true } = {}) => {
  const user = await prisma.appUser.findFirst({ where: { email } });
  const { text, payload } = generated();
  return prisma.generatedPlan.create({
    data: {
      userId: user.id,
      legacyId: `plan-${email}`,
      goal: FIELDS.goal,
      equipment: FIELDS.equipment,
      durationMinutes: FIELDS.duration,
      level: FIELDS.level,
      injuries: FIELDS.injuries,
      days: FIELDS.days,
      environment: FIELDS.environment,
      focuses: FIELDS.focuses,
      planText: text,
      planPayload: structured ? payload : {}
    }
  });
};

const pathOf = (planId) => `/api/dashboard/plans/${encodeURIComponent(planId)}/swaps`;
const optionsPath = (planId, exercise, area) =>
  `${pathOf(planId)}?exercise=${encodeURIComponent(exercise)}${area ? `&area=${encodeURIComponent(area)}` : ""}`;
const mondayOf = (plan) => plan.payload.days.find((day) => day.weekday === "Monday");

describe("the plan swap routes", () => {
  let agent;
  let csrfToken;
  let row;
  const EMAIL = "plan-swaps@example.com";

  const post = (path, body) => agent.post(path).set("X-CSRF-Token", csrfToken).send(body);
  const swap = (body) => post(pathOf(row.legacyId), body);

  beforeAll(async () => {
    await prisma.$connect();
  });

  afterAll(async () => {
    await prisma.appUser.deleteMany({});
    await prisma.$disconnect();
  });

  beforeEach(async () => {
    await prisma.appUser.deleteMany({});
    agent = request.agent(app);
    csrfToken = await signUp(agent, EMAIL);
    row = await savePlan(EMAIL);
  });

  test("each route needs a session", async () => {
    const stranger = request.agent(app);
    const token = await getCsrf(stranger);
    const responses = await Promise.all([
      stranger.get(optionsPath(row.legacyId, GOBLET)),
      stranger
        .post(pathOf(row.legacyId))
        .set("X-CSRF-Token", token)
        .send({ from: GOBLET, to: SUMO }),
      stranger
        .post(`${pathOf(row.legacyId)}/undo`)
        .set("X-CSRF-Token", token)
        .send({ name: SUMO })
    ]);
    expect(responses.map((response) => response.status)).toEqual([401, 401, 401]);
  });

  test("lists the alternatives under the plan's rules, and an area's", async () => {
    const saved = mapGeneratedPlan(row);

    const plain = await agent.get(optionsPath(row.legacyId, GOBLET));
    expect(plain.status).toBe(200);
    expect(plain.body).toEqual({
      exercise: GOBLET,
      area: null,
      areas: SWAP_AREAS,
      alternatives: swapOptions(saved, GOBLET, rulesForPlan(saved, { age: AGE, area: null }))
    });
    expect(plain.body.alternatives.map((option) => option.name)).toContain(SUMO);

    const knee = await agent.get(optionsPath(row.legacyId, GOBLET, "knee"));
    expect(knee.status).toBe(200);
    expect(knee.body.alternatives).toEqual(
      swapOptions(saved, GOBLET, rulesForPlan(saved, { age: AGE, area: "knee" }))
    );
    expect(knee.body.alternatives).not.toEqual(plain.body.alternatives);
  });

  test("finds the plan by its id as well as its legacy id", async () => {
    const response = await agent.get(optionsPath(row.id, GOBLET));
    expect(response.status).toBe(200);
    expect(response.body.exercise).toBe(GOBLET);
  });

  test("a bad question is a 400: an exercise not in the plan, an area not offered", async () => {
    const responses = await Promise.all([
      agent.get(optionsPath(row.legacyId, "Barbell back squat")),
      agent.get(optionsPath(row.legacyId, GOBLET, "pregnancy")),
      agent.get(pathOf(row.legacyId))
    ]);
    expect(responses.map((response) => response.status)).toEqual([400, 400, 400]);
    expect(responses[0].body).toEqual({ error: "That exercise is not in this plan." });
  });

  test("another user's plan, or one with no saved structure, is a 404", async () => {
    const other = await prisma.appUser.create({
      data: { email: "plan-swaps-other@example.com", passwordHash: "x" }
    });
    const theirs = await prisma.generatedPlan.create({
      data: {
        userId: other.id,
        legacyId: "their-plan",
        planText: row.planText,
        planPayload: row.planPayload
      }
    });
    await prisma.generatedPlan.update({ where: { id: row.id }, data: { planPayload: {} } });

    const responses = await Promise.all([
      agent.get(optionsPath(theirs.legacyId, GOBLET)),
      post(pathOf(theirs.legacyId), { from: GOBLET, to: SUMO }),
      post(`${pathOf(theirs.legacyId)}/undo`, { name: SUMO }),
      agent.get(optionsPath(row.legacyId, GOBLET)),
      swap({ from: GOBLET, to: SUMO })
    ]);
    expect(responses.map((response) => response.status)).toEqual([404, 404, 404, 404, 404]);
    expect(responses[0].body).toEqual({ error: "That plan was not found." });
    expect(responses[3].body).toEqual({ error: "That plan has no saved structure to swap in." });
  });

  test("a swap rewrites the plan, which the dashboard then reads", async () => {
    const response = await swap({ from: GOBLET, to: SUMO, area: null });

    expect(response.status).toBe(200);
    const [first] = mondayOf(response.body.plan).prescriptions;
    expect(first).toMatchObject({ name: SUMO, swapReason: null });
    expect(first.swappedFrom.prescription.name).toBe(GOBLET);

    const dashboard = await agent.get("/api/dashboard");
    const [plan] = dashboard.body.dashboard.plans;
    expect(plan.payload).toEqual(response.body.plan.payload);
    expect(plan.plan).toContain(`- A1. ${SUMO}: `);
    expect(plan.plan).not.toContain(GOBLET);
  });

  test("a swap the plan cannot take is a 409, and changes nothing", async () => {
    const responses = [
      await swap({ from: GOBLET, to: "Push-up" }),
      await swap({ from: "Barbell back squat", to: SUMO })
    ];
    expect(responses.map((response) => response.status)).toEqual([409, 409]);
    expect(responses[0].body).toEqual({ error: "The plan has changed. Reload it and try again." });

    const stored = await prisma.generatedPlan.findUnique({ where: { id: row.id } });
    expect(stored.planText).toBe(row.planText);
  });

  test("a body that is not a swap is a 400", async () => {
    const responses = await Promise.all([
      swap({ from: GOBLET }),
      swap({ from: GOBLET, to: SUMO, area: "pregnancy" }),
      post(`${pathOf(row.legacyId)}/undo`, {})
    ]);
    expect(responses.map((response) => response.status)).toEqual([400, 400, 400]);
  });

  test("a plan id longer than any plan's is a 400 on every route", async () => {
    const long = "p".repeat(101);
    const responses = await Promise.all([
      agent.get(optionsPath(long, GOBLET)),
      post(pathOf(long), { from: GOBLET, to: SUMO }),
      post(`${pathOf(long)}/undo`, { name: SUMO })
    ]);
    expect(responses.map((response) => response.status)).toEqual([400, 400, 400]);
  });

  test("the undo puts back the plan as generated, and is a 409 with nothing swapped", async () => {
    await swap({ from: GOBLET, to: SUMO, area: "wrist" });

    const undone = await post(`${pathOf(row.legacyId)}/undo`, { name: SUMO });
    expect(undone.status).toBe(200);
    expect(undone.body.plan.payload).toEqual(mapGeneratedPlan(row).payload);
    expect(undone.body.plan.plan).toBe(row.planText);

    const again = await post(`${pathOf(row.legacyId)}/undo`, { name: SUMO });
    expect(again.status).toBe(409);
    expect(again.body).toEqual({ error: "That exercise has no swap to undo." });
  });

  test("two swaps sent at once both land", async () => {
    const monday = mondayOf(mapGeneratedPlan(row));
    const hinge = monday.prescriptions[2].name;
    const saved = mapGeneratedPlan(row);
    const [hingeOption] = swapOptions(saved, hinge, rulesForPlan(saved, { age: AGE, area: null }));

    const responses = await Promise.all([
      swap({ from: GOBLET, to: SUMO }),
      swap({ from: hinge, to: hingeOption.name })
    ]);
    expect(responses.map((response) => response.status)).toEqual([200, 200]);

    const names = mondayOf(
      mapGeneratedPlan(await prisma.generatedPlan.findUnique({ where: { id: row.id } }))
    ).prescriptions.map((p) => p.name);
    expect(names).toEqual(expect.arrayContaining([SUMO, hingeOption.name]));
    expect(names).not.toContain(GOBLET);
    expect(names).not.toContain(hinge);
  });
});
